"""Brain tool `advisor_prep` (catalog executor "brain"; interface in cloud/tools_interface.md).

"prep me for my meeting with the Hendersons" ->
  1. normalize the client reference by code ("meeting with the hendersons" -> "henderson"), then fuzzy-match a
     household folder under ~/Documents/Clients (or $MUSELET_CLIENTS_DIR)
  2. Calendar: shown with `skill open_app` only; the meeting time comes from the folder's annual_review.ics
     (no Calendar scripting, so no Automation prompt)       } concurrently: brain.advisor.prep reads
  3. Finder: reveal the folder (skill open_folder)         } the folder's files from disk in a thread
  4. Numbers: open portfolio.xlsx (skill open_file), wait for the document
  5. (prep result)  6. Numbers: highlight TLH lots + Review sheet  7. Notes: write + show the brief
  8. final bubble: opportunity count (deterministic; amounts are different kinds, so they are never summed).
Each app step has a 5 s timeout. Calendar, Finder and Numbers are optional: on timeout or error a short bubble
says so and the run continues without that step. The Notes brief is required.
Every number comes from brain.advisor; the scripts are generated by brain.advisor.scripts with all values escaped.
"""

from __future__ import annotations

import asyncio
import datetime as dt
import difflib
import os
import re
import time
import unicodedata
from pathlib import Path

from brain import advisor

NAME = "advisor_prep"
PAUSE_S = 0.25            # <= 300 ms so the viewer sees each app come forward
FUZZY_MIN = 0.85
REQUIRED_FILES = ("portfolio.csv", "portfolio.xlsx", "activity_last_60d.csv", "profile.json", "targets.json")
STOPWORDS = {"the", "a", "an", "my", "our", "their", "household", "households", "family", "families", "client",
             "clients", "meeting", "meetings", "review", "annual", "with", "for", "and", "mr", "mrs", "ms", "dr",
             "folder", "account", "accounts", "prep"}


def clients_root() -> Path:
    return Path(os.environ.get("MUSELET_CLIENTS_DIR") or Path.home() / "Documents" / "Clients")


def _tokens(text: str) -> list[str]:
    s = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode().lower()
    s = re.sub(r"['\u2019]s\b", "", s.replace("\u2019", "'")).replace("'", "")
    return [t for t in re.findall(r"[a-z0-9]+", s) if t not in STOPWORDS]


def _variants(tok: str) -> set[str]:
    out = {tok}
    if len(tok) > 3 and tok.endswith("es"):
        out.add(tok[:-2])
    if len(tok) > 2 and tok.endswith("s"):
        out.add(tok[:-1])
    return out


def _tok_score(q: str, f: str) -> float:
    best = 0.0
    for v in _variants(q):
        if v == f:
            return 1.0
        if v[:1] == f[:1]:   # typos, not different names ("Andersons" is not "Henderson")
            best = max(best, difflib.SequenceMatcher(None, v, f).ratio())
    return best


_LEAD = re.compile(
    r"^(?:(?:please|can you|could you|help me|get me ready|get ready|ready me|prep me|prepare me|prep|prepare|"
    r"brief me|set me up)\s+)*"
    r"(?:(?:for|on|about)\s+)?"
    r"(?:(?:my|our|the|an?|next|upcoming|today'?s|tomorrow'?s)\s+)*"
    r"(?:(?:annual |quarterly |client )?(?:meeting|call|review|check-?in|appointment|session)s?\s+"
    r"(?:with|for|of)\s+)?"
    r"(?:(?:prep|review|brief)\s+(?:for|on|of)\s+)?"
    r"(?:(?:the|my|our|mr\.?|mrs\.?|ms\.?|dr\.?)\s+)*", re.IGNORECASE)
_TAIL = re.compile(r"\s+(?:household|family|clients?|folder|account|accounts|portfolio|meeting|review)s?$", re.IGNORECASE)


def normalize_client(client: str) -> str:
    """Spoken client reference -> bare name, by code: 'meeting with the hendersons' -> 'Henderson',
    "the Henderson's" -> 'Henderson', 'the Henderson household' -> 'Henderson'. Plurals/possessives
    are reduced to the singular surname only for the last word."""
    s = unicodedata.normalize("NFKC", client).replace("\u2019", "'").strip().strip(".,!?;:\"").strip()
    s = re.sub(r"\s+", " ", s)
    prev = None
    while prev != s:
        prev = s
        s = _TAIL.sub("", _LEAD.sub("", s, count=1)).strip()
    s = re.sub(r"(?i)^(.*?)(?:'s|s'|')$", r"\1", s)
    words = s.split(" ")
    if words and words[-1]:
        w = words[-1]
        if re.fullmatch(r"(?i)[a-z]{2,}(?:ch|sh|x|z|ss|[aeiou]s)es", w):
            w = w[:-2]
        elif re.fullmatch(r"(?i)[a-z]{3,}[^s]s", w):
            w = w[:-1]
        words[-1] = w
    return " ".join(words).strip()


def match_client(client: str, names: list[str]) -> tuple[str | None, list[str]]:
    """Best folder name for a spoken client reference -> (name or None, tied names when ambiguous)."""
    for q in (_tokens(normalize_client(client)), _tokens(client)):   # raw tokens: "Chris", "Moses"
        hit = _match_tokens(q, names)
        if hit[0] or hit[1]:
            return hit
    return None, []


def _match_tokens(q: list[str], names: list[str]) -> tuple[str | None, list[str]]:
    scored = []
    for name in names:
        f = _tokens(name)
        if not q or not f:
            continue
        per_f = [max(_tok_score(t, ft) for t in q) for ft in f]
        best = max(per_f)
        if best >= FUZZY_MIN:
            folder_cov = sum(1 for x in per_f if x >= FUZZY_MIN) / len(f)
            query_cov = sum(1 for t in q if max(_tok_score(t, ft) for ft in f) >= FUZZY_MIN) / len(q)
            scored.append(((round(best, 4), folder_cov, query_cov), name))
    if not scored:
        return None, []
    scored.sort(key=lambda x: (x[0], x[1]), reverse=True)
    top = [n for s, n in scored if s == scored[0][0]]
    return (top[0], []) if len(top) == 1 else (None, sorted(top))


def find_household(client: str, root: Path | None = None) -> tuple[Path | None, list[str]]:
    root = root or clients_root()
    if not root.is_dir():
        return None, []
    names = sorted(p.name for p in root.iterdir() if p.is_dir() and not p.name.startswith("."))
    name, ties = match_client(client, names)
    return (root / name if name else None), ties


def _surname(folder: Path) -> str:
    words = [w for w in re.split(r"[\s_,&-]+", folder.name) if w and w.lower() not in STOPWORDS]
    return words[0] if words else folder.name


def display_name(folder: Path) -> str:
    """'Henderson' -> 'the Hendersons' (folder words such as 'Household' are dropped)."""
    base = _surname(folder)
    plural = base + ("es" if re.search(r"(s|x|z|ch|sh)$", base, re.IGNORECASE) else "s")
    return f"the {plural}"


def _possessive(name: str) -> str:
    return name + "'"


def final_bubble(prep: dict, skipped: list[str] | None = None) -> str:
    n = len(prep["opportunities"])
    head = "No opportunities found." if n == 0 else f"{n} opportunit{'y' if n == 1 else 'ies'} found."
    if skipped:
        return f"{head} Brief in Notes; skipped {', '.join(skipped)}."
    return f"{head} Brief is in Notes."


def _load_prep(folder: Path) -> dict:
    return advisor.prep(advisor.load_household(folder))


def _trace(orch, kind: str, *args) -> None:
    fn = getattr(getattr(orch, "tracer", None), kind, None)
    if callable(fn):
        fn(*args)


class _Failed(Exception):
    def __init__(self, bubble: str, raw: str):
        super().__init__(raw)
        self.bubble = bubble


STEP_TIMEOUT_S = 5.0
NUMBERS_WAIT_TRIES = 40   # x 0.1 s polling inside the script, so it answers before the step timeout


class _Skipped(Exception):
    pass


async def _rpc(orch, stage: str, bubble_on_fail: str, method: str, params: dict,
               timeout: float | None = None, optional: str | None = None) -> dict | None:
    """One step, <= `timeout` s. Failure or timeout: a required step raises _Failed; an optional step shows
    `optional` (a short "continuing" bubble), raises _Skipped to the caller's step block and the run goes on."""
    timeout = STEP_TIMEOUT_S if timeout is None else timeout
    t = time.perf_counter()
    try:
        res = await asyncio.wait_for(orch.server.rpc(method, params, timeout=timeout), timeout + 0.5)
    except (RuntimeError, TimeoutError) as e:
        ms = (time.perf_counter() - t) * 1000
        timed_out = isinstance(e, TimeoutError) or "timed out" in str(e)
        _trace(orch, "rpc", method, params, {"error": str(e) or "timeout", "timeout": timed_out}, ms)
        _trace(orch, "stage", f"{NAME}.{stage}", ms)
        if optional:
            await orch.server.ui("acting", optional)
            raise _Skipped(stage) from e
        raise _Failed(bubble_on_fail, f"{stage}: {'timeout' if timed_out else e}") from e
    ms = (time.perf_counter() - t) * 1000
    _trace(orch, "rpc", method, params, res, ms)
    _trace(orch, "stage", f"{NAME}.{stage}", ms)
    if not isinstance(res, dict) or not res.get("ok", False):
        err = res.get("error", "?") if isinstance(res, dict) else repr(res)
        if optional:
            await orch.server.ui("acting", optional)
            raise _Skipped(stage)
        raise _Failed(bubble_on_fail, f"{stage}: {err}")
    return res


def _script(code: str) -> dict:
    return {"op": "script", "lang": "applescript", "code": code}


def meeting_line(meeting: dict, who: str) -> str:
    """Bubble for the review time taken from the folder's annual_review.ics (no Calendar read, no prompt)."""
    if not meeting.get("start"):
        return f"No meeting file for {who}; continuing."
    start = dt.datetime.fromisoformat(meeting["start"])
    return f"Review {start:%a %b} {start.day}, {start:%H:%M}, per the client file."


async def run(orch, args: dict, utterance: str) -> str:
    t0 = time.perf_counter()
    raw = str(args.get("client") or "").strip()
    client = normalize_client(raw) or raw
    server = orch.server
    await server.ui("thinking", "Finding the client folder...")
    folder, ties = find_household(raw)
    if folder is None:
        _trace(orch, "decision", {"tool": NAME, "client": raw, "normalized": client, "root": str(clients_root()),
                                  "ties": ties})
        msg = (f"Two client folders match {client}; which one?" if len(ties) > 1
               else f"No client folder for {client or 'that client'}.")
        if len(msg.split()) > 12:
            msg = "Which client folder did you mean?" if ties else "I couldn't find that client folder."
        await server.say(msg)
        await server.ui("confused")
        return "failed"
    who = display_name(folder)
    whose = _possessive(who)
    missing = [f for f in REQUIRED_FILES if not (folder / f).is_file()]
    if missing:
        _trace(orch, "decision", {"tool": NAME, "folder": str(folder), "missing": missing})
        await server.say(f"Couldn't find {whose} portfolio files.")
        await server.ui("confused")
        return "failed"
    prep_task = asyncio.create_task(asyncio.to_thread(_load_prep, folder))
    skipped: list[str] = []
    xlsx = os.path.realpath(folder / "portfolio.xlsx")
    try:
        await server.ui("acting", f"Checking your calendar for {who}...")
        ics = folder / "annual_review.ics"
        meeting = advisor.parse_ics(ics.read_text()) if ics.is_file() else {}
        try:
            await _rpc(orch, "calendar", "", "skill", {"name": "open_app", "args": {"app": "Calendar"}},
                       optional="Calendar didn't open in time; continuing.")
            await server.ui("acting", meeting_line(meeting, who))
            await asyncio.sleep(PAUSE_S)
        except _Skipped:
            skipped.append("Calendar")

        await server.ui("acting", f"Opening {whose} client folder...")
        try:
            await _rpc(orch, "finder", "", "skill", {"name": "open_folder", "args": {"path": str(folder)}},
                       optional="Finder didn't open in time; continuing.")
            await asyncio.sleep(PAUSE_S)
        except _Skipped:
            skipped.append("Finder")

        await server.ui("acting", f"Reading {whose} portfolio...")
        numbers = True
        try:
            await _rpc(orch, "open_portfolio", "", "skill", {"name": "open_file", "args": {"path": xlsx}},
                       optional="Numbers didn't open in time; continuing.")
            await _rpc(orch, "numbers_ready", "", "act",
                       _script(advisor.numbers_wait_script(xlsx, tries=NUMBERS_WAIT_TRIES)),
                       optional="Numbers didn't open the portfolio; continuing.")
        except _Skipped:
            numbers = False

        await server.ui("thinking", "Running the numbers on this Mac...")
        t = time.perf_counter()
        try:
            prep = await prep_task
        except (OSError, ValueError, KeyError) as e:
            raise _Failed(f"Couldn't read {whose} files.", f"prep: {e!r}") from e
        _trace(orch, "stage", f"{NAME}.prep_wait", (time.perf_counter() - t) * 1000)
        _trace(orch, "decision", {"tool": NAME, "client": raw, "normalized": client, "folder": str(folder),
                                  "document": xlsx, "meeting": meeting, "meeting_source": str(ics),
                                  "prep": prep})

        if numbers:
            await server.ui("acting", "Highlighting opportunities in Numbers...")
            for stage, code, bubble in (
                    ("numbers_highlight", advisor.numbers_highlight_script(prep, path=xlsx),
                     "Couldn't highlight the sheet in time; continuing."),
                    ("numbers_review", advisor.numbers_review_script(prep, path=xlsx),
                     "Couldn't add the Review sheet in time; continuing.")):
                try:
                    await _rpc(orch, stage, "", "act", _script(code), optional=bubble)
                except _Skipped:
                    numbers = False
        if not numbers:
            skipped.append("Numbers")

        await server.ui("acting", "Writing the brief in Notes...")
        await _rpc(orch, "notes_brief", "Couldn't write the brief in Notes.", "act",
                   _script(advisor.notes_brief_script(prep, phrasing=None, reveal=True)))
    except _Failed as f:
        _trace(orch, "decision", {"tool": NAME, "error": str(f), "skipped": skipped})
        await server.say(f.bubble)
        await server.ui("confused")
        return "failed"
    finally:
        if not prep_task.done():
            prep_task.cancel()
    _trace(orch, "stage", NAME, (time.perf_counter() - t0) * 1000)
    _trace(orch, "decision", {"tool": NAME, "skipped": skipped})
    await server.ui("success")
    await server.say(final_bubble(prep, skipped))
    return "ok"
