"""Generate pinned real System One requests from the research checkouts."""

from __future__ import annotations

import argparse
import gzip
import json
import sys
from pathlib import Path
from typing import Any

BRAIN_SHA = "dadf97d01512f6384ca8bfd90a77cc88ae1a2f43"
JEVBENCH_SHA = "609a664e81f46e03731600bd7bd9f1b7a61257c5"
TYPED_DECISIONS_REVISION = "80cb93ae477fdfc91e3b6114f7a281c444dda843"
ROOT = Path(__file__).resolve().parent


def _write(path: Path, value: Any) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def _payload(row: dict) -> dict:
    return {key: row[key] for key in ("state", "questions", "model") if key in row}


def _brain_examples(brain: Path) -> list[tuple[str, str, dict]]:
    records: list[tuple[str, str, dict]] = []
    example_path = brain / "examples" / "request.json"
    example = json.loads(example_path.read_text(encoding="utf-8"))
    records.append(("brain-request.json", "examples/request.json", _payload(example)))

    fixtures = brain / "fixtures" / "replay" / "v1"
    with gzip.open(fixtures / "gym.jsonl.gz", "rt", encoding="utf-8") as stream:
        gym = next(json.loads(line) for line in stream if line.strip())
    records.append(("gym.json", f"fixtures/replay/v1/gym.jsonl.gz row id={gym['id']}", _payload(gym)))
    with gzip.open(fixtures / "large.jsonl.gz", "rt", encoding="utf-8") as stream:
        large = next(
            row for row in (json.loads(line) for line in stream if line.strip())
            if any(
                len(question.get("criteria", {})) > 58
                for question in row.get("questions", {}).values()
                if isinstance(question.get("criteria"), (dict, list))
            )
        )
    records.append(("large.json", f"fixtures/replay/v1/large.jsonl.gz row id={large['id']}", _payload(large)))
    return records


def _jev_examples(jevbench: Path) -> list[tuple[str, str, dict]]:
    sys.path.insert(0, str(jevbench))
    from jevbench.adapters.typesafe import TypeSafeAdapter
    from jevbench.tasks import load_jsonl

    adapter = TypeSafeAdapter(model="muselet")
    records = []
    seen_types: set[str] = set()
    for split in ("original", "easy", "hard"):
        path = jevbench / "datasets" / "public" / f"{split}.jsonl"
        tasks = load_jsonl(str(path))
        task = next((item for item in tasks if item.question["type"] not in seen_types), tasks[0])
        seen_types.add(task.question["type"])
        records.append((
            f"{split}.json",
            f"datasets/public/{split}.jsonl row id={task.id}; TypeSafeAdapter.build_request",
            adapter.build_request(task),
        ))
    return records


def _typed_examples(typed: Path) -> list[tuple[str, str, dict]]:
    import pyarrow.parquet as parquet

    source = typed / "all" / "test-00000-of-00001.parquet"
    rows = parquet.read_table(source).to_pylist()[:3]
    records = []
    for index, row in enumerate(rows, start=1):
        records.append((
            f"test-{index}.json",
            f"all/test-00000-of-00001.parquet row id={row['id']}; score_with_jobs.py payload",
            {
                "model": "muselet",
                "state": json.loads(row["state"]),
                "questions": json.loads(row["questions"]),
            },
        ))
    return records


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--brain-dir", type=Path, default=Path("/home/ubuntu/ext/deskmind-ai__brain"))
    parser.add_argument("--jevbench-dir", type=Path, default=Path("/home/ubuntu/ext/fstandhartinger__jevbench"))
    parser.add_argument("--typed-dir", type=Path, default=Path("/home/ubuntu/ext/td"))
    args = parser.parse_args()

    sections = (
        ("deskmind", "deskmind-ai/brain", BRAIN_SHA, _brain_examples(args.brain_dir)),
        ("jevbench", "fstandhartinger/jevbench", JEVBENCH_SHA, _jev_examples(args.jevbench_dir)),
        ("typed_decisions", "LocalLLaMA/typed-decisions", TYPED_DECISIONS_REVISION, _typed_examples(args.typed_dir)),
    )
    manifest = ["# Saved System One requests", "", "Generated by `python3 -m bench.systemone.examples.build_examples`.", ""]
    for directory, repository, revision, rows in sections:
        manifest.extend([f"## {directory}", "", f"- Repository: `{repository}`", f"- Revision: `{revision}`", ""])
        target = ROOT / directory
        target.mkdir(parents=True, exist_ok=True)
        for filename, source, request in rows:
            _write(target / filename, request)
            manifest.append(f"- `{directory}/{filename}`: `{source}`")
        manifest.append("")
    (ROOT / "README.md").write_text("\n".join(manifest) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
